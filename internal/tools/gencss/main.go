// Command gencss writes the default theme's code colours:
//
//	go run ./internal/tools/gencss themes/default/assets/css/code.css
package main

import (
	"fmt"
	"math"
	"os"
	"regexp"
	"strconv"
	"strings"

	"github.com/GTKottman/skimdit/internal/markdown"
)

var (
	comment = regexp.MustCompile(`/\*[^*]*\*/`)
	space   = regexp.MustCompile(`\s+`)
)

func minify(css string) string {
	var out []string
	for _, line := range strings.Split(css, "\n") {
		line = strings.TrimSpace(comment.ReplaceAllString(line, ""))
		// The theme sets its own code background and line numbers.
		if line == "" || strings.Contains(line, ".bg ") || strings.Contains(line, ".chroma {") || strings.Contains(line, ".lnt") || strings.Contains(line, ".ln ") || strings.Contains(line, ".hl ") {
			continue
		}
		out = append(out, space.ReplaceAllString(line, " "))
	}
	return strings.Join(out, "\n")
}

var hexRe = regexp.MustCompile(`#[0-9a-fA-F]{6}`)

// fix raises every colour in css to at least min contrast against each
// background, moving lightness away from the backgrounds (up on dark, down on light).
func fix(css string, bgs []string, lighten bool, min float64) string {
	return hexRe.ReplaceAllStringFunc(css, func(c string) string {
		r, g, b := rgb(c)
		for i := 0; i < 100 && worst(r, g, b, bgs) < min; i++ {
			if lighten {
				r, g, b = r+(1-r)*0.06, g+(1-g)*0.06, b+(1-b)*0.06
			} else {
				r, g, b = r*0.94, g*0.94, b*0.94
			}
		}
		return fmt.Sprintf("#%02x%02x%02x", int(r*255+0.5), int(g*255+0.5), int(b*255+0.5))
	})
}

func rgb(h string) (float64, float64, float64) {
	v := func(i int) float64 {
		n, _ := strconv.ParseUint(h[1+2*i:3+2*i], 16, 8)
		return float64(n) / 255
	}
	return v(0), v(1), v(2)
}

func lum(r, g, b float64) float64 {
	f := func(x float64) float64 {
		if x <= 0.03928 {
			return x / 12.92
		}
		return math.Pow((x+0.055)/1.055, 2.4)
	}
	return 0.2126*f(r) + 0.7152*f(g) + 0.0722*f(b)
}

func worst(r, g, b float64, bgs []string) float64 {
	w := math.Inf(1)
	l := lum(r, g, b)
	for _, bg := range bgs {
		m := lum(rgb(bg))
		hi, lo := math.Max(l, m), math.Min(l, m)
		w = math.Min(w, (hi+0.05)/(lo+0.05))
	}
	return w
}

// The code backgrounds of the default theme: the field colour and the
// highlighted-line band (field mixed with 14% of the default accent).
var (
	darkBGs  = []string{"#1d2433", "#2b3850"}
	lightBGs = []string{"#e8e3d8", "#d9dbd9"}
)

func main() {
	dark, err := markdown.HighlightCSS("github-dark", "")
	if err != nil {
		panic(err)
	}
	light, err := markdown.HighlightCSS("github", `:root[data-theme="light"]`)
	if err != nil {
		panic(err)
	}
	auto, err := markdown.HighlightCSS("github", `:root:not([data-theme="dark"])`)
	if err != nil {
		panic(err)
	}
	dark = fix(minify(dark), darkBGs, true, 4.6)
	light = fix(minify(light), lightBGs, false, 4.6)
	auto = fix(minify(auto), lightBGs, false, 4.6)
	out := "/* Code colours, generated by internal/tools/gencss from chroma's github-dark and github styles,\n   adjusted to at least 4.6:1 contrast on the theme's code backgrounds. */\n" +
		dark + "\n" + light + "\n@media (prefers-color-scheme: light) {\n" + auto + "\n}\n"
	if err := os.WriteFile(os.Args[1], []byte(out), 0o644); err != nil {
		panic(err)
	}
	fmt.Println(len(out), "bytes")
}
