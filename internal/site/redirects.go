// LedgerFile lists every URL the site has ever published, so a URL can
// never silently disappear. It belongs in git.
const LedgerFile = "published-urls.txt"

// RedirectsFile holds hand-written and automatically recorded redirects.
const RedirectsFile = "redirects.toml"

// Gone marks a URL that was removed on purpose (served as 410 Gone).
const Gone = "gone"

type redirectsDoc struct {
	Redirects map[string]string `toml:"redirects"`
}

func (b *Build) loadRedirects() (map[string]string, error) {
	path := filepath.Join(b.Config.Root, RedirectsFile)
	var doc redirectsDoc
	md, err := toml.DecodeFile(path, &doc)
	if errors.Is(err, fs.ErrNotExist) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("%s: %w", RedirectsFile, err)
	}
	if und := md.Undecoded(); len(und) > 0 {
		return nil, fmt.Errorf("%s: unknown key %s (use a [redirects] table)", RedirectsFile, und[0])
	}
	out := map[string]string{}
	for from, to := range doc.Redirects {
		if !strings.HasPrefix(from, "/") || (to != Gone && !strings.HasPrefix(to, "/") && !strings.HasPrefix(to, "https://")) {
			return nil, fmt.Errorf("%s: %q = %q: paths start with /, targets are paths, https URLs or \"gone\"", RedirectsFile, from, to)
		}
		out[b.Config.Rel(from)] = to
		if to != Gone && strings.HasPrefix(to, "/") {
			out[b.Config.Rel(from)] = b.Config.Rel(to)
		}
	}
	return out, nil
}

type ledgerEntry struct{ url, source string }

func (b *Build) loadLedger() ([]ledgerEntry, error) {
	f, err := os.Open(filepath.Join(b.Config.Root, LedgerFile))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []ledgerEntry
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		u, src, _ := strings.Cut(line, "\t")
		out = append(out, ledgerEntry{u, src})
	}
	return out, sc.Err()
}

// redirectsFile checks the ledger, records moved URLs, writes redirect
// pages and the _redirects file the server reads.
func (b *Build) redirectsFile() error {
	cfg := b.Config
	manual, err := b.loadRedirects()
	if err != nil {
		b.diag(RedirectsFile, 0, false, "%v", err)
		return nil
	}
	ledger, err := b.loadLedger()
	if err != nil {
		return err
	}
	bySource := map[string]*Entry{}
	for _, e := range b.Entries {
		bySource[e.Source] = e
	}
	recorded := false
	for _, le := range ledger {
		if _, live := b.byURL[le.url]; live {
			continue
		}
		if _, ok := b.Redirect[le.url]; ok {
			continue
		}
		if _, ok := manual[le.url]; ok {
			continue
		}
		if e := bySource[le.source]; e != nil {
			if b.Opts.RecordURLs {
				manual[le.url] = e.URL
				recorded = true
				continue
			}
			b.diag(le.source, 0, false, "the URL %s was published but this post now lives at %s; run `skimdit build` to record the redirect, or add it to %s", le.url, e.URL, RedirectsFile)
			continue
		}
		if b.Opts.Drafts {
			continue // the dev server shows a work in progress
		}
		b.diag(LedgerFile, 0, false, "%s was published (from %s) and would now be a dead link; add a redirect to %s (\"%s\" = \"/new/\" or \"gone\")", le.url, le.source, RedirectsFile, strings.TrimPrefix(le.url, strings.TrimSuffix(cfg.Site.BasePath, "/")))
	}
	if recorded {
		if err := b.saveRedirects(manual); err != nil {
			return err
		}
	}

	// Collapse chains and render a page for each manual redirect.
	all := map[string]string{}
	for k, v := range b.Redirect {
		all[k] = v
	}
	for k, v := range manual {
		if _, live := b.byURL[k]; live {
			b.diag(RedirectsFile, 0, false, "redirect from %s hides a live page; remove it", k)
			continue
		}
		all[k] = v
	}
	resolve := func(from string) (string, error) {
		seen := map[string]bool{from: true}
		to := all[from]
		for {
			next, ok := all[to]
			if !ok {
				return to, nil
			}
			if seen[to] {
				return "", fmt.Errorf("redirect loop through %s", to)
			}
			seen[to] = true
			to = next
		}
	}
	froms := make([]string, 0, len(all))
	for k := range all {
		froms = append(froms, k)
	}
	sort.Strings(froms)
	var out strings.Builder
	out.WriteString("# Generated by Skimdit: from to status\n")
	for _, from := range froms {
		to, err := resolve(from)
		if err != nil {
			b.diag(RedirectsFile, 0, false, "%v", err)
			continue
		}
		if to == Gone {
			fmt.Fprintf(&out, "%s %s 410\n", from, from)
			continue
		}
		if strings.HasPrefix(to, "/") {
			target := strings.SplitN(to, "#", 2)[0]
			if _, live := b.byURL[target]; !live && !b.fileWritten(b.urlFile(target)) {
				b.diag(RedirectsFile, 0, false, "redirect %s points at %s, which does not exist", from, to)
				continue
			}
		}
		fmt.Fprintf(&out, "%s %s 301\n", from, to)
		if _, isAlias := b.Redirect[from]; !isAlias {
			if err := b.redirect(from, to); err != nil {
				return err
			}
		}
	}
	if err := b.write("_redirects", []byte(out.String()), "redirects"); err != nil {
		return err
	}
	if b.Opts.RecordURLs {
		return b.saveLedger(ledger)
	}
	return nil
}

func (b *Build) fileWritten(p string) bool {
	b.fmu.Lock()
	defer b.fmu.Unlock()
	_, ok := b.files[p]
	return ok
}

func (b *Build) saveRedirects(m map[string]string) error {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var s strings.Builder
	s.WriteString("# Redirects. Skimdit adds a line here when a published URL moves.\n# \"/old/\" = \"/new/\" sends readers on; \"/old/\" = \"gone\" answers 410 Gone.\n\n[redirects]\n")
	base := strings.TrimSuffix(b.Config.Site.BasePath, "/")
	for _, k := range keys {
		v := m[k]
		if strings.HasPrefix(v, "/") {
			v = strings.TrimPrefix(v, base)
		}
		fmt.Fprintf(&s, "%q = %q\n", strings.TrimPrefix(k, base), v)
	}
	return os.WriteFile(filepath.Join(b.Config.Root, RedirectsFile), []byte(s.String()), 0o644)
}

func (b *Build) saveLedger(old []ledgerEntry) error {
	m := map[string]string{}
	for _, le := range old {
		m[le.url] = le.source
	}
	changed := false
	for _, e := range b.Entries {
		if e.doc == nil || e.Status == "draft" || e.Date.After(b.Now) {
			continue
		}
		if src, ok := m[e.URL]; !ok || src != e.Source {
			m[e.URL] = e.Source
			changed = true
		}
	}
	if !changed && len(old) > 0 {
		return nil
	}
	urls := make([]string, 0, len(m))
	for u := range m {
		urls = append(urls, u)
	}
	sort.Strings(urls)
	var s strings.Builder
	s.WriteString("# Every URL this site has published, with the file it came from.\n# Skimdit keeps this file; commit it. A URL listed here may never become a dead link.\n")
	for _, u := range urls {
		s.WriteString(u + "\t" + m[u] + "\n")
	}
	return os.WriteFile(filepath.Join(b.Config.Root, LedgerFile), []byte(s.String()), 0o644)
}
